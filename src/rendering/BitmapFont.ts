export const GLYPH_WIDTH = 5;
export const GLYPH_HEIGHT = 7;
/** Spazio orizzontale occupato da ogni carattere (glifo + 1 pixel). */
export const GLYPH_ADVANCE = GLYPH_WIDTH + 1;

const ACCENT_REPLACEMENTS: Record<string, string> = {
  "à": "A", "á": "A", "è": "E", "é": "E", "ì": "I", "í": "I",
  "ò": "O", "ó": "O", "ù": "U", "ú": "U",
};

/** Restituisce le righe del glifo per un carattere (con fallback a '?'). */
export function getGlyphRows(character: string): string[] {
  const replaced = ACCENT_REPLACEMENTS[character] ?? character.toUpperCase();
  return GLYPH_ROWS[replaced] ?? GLYPH_ROWS["?"]!;
}

/** Larghezza in pixel di un testo disegnato con la scala indicata. */
export function measureTextWidth(text: string, scale: number): number {
  if (text.length === 0) {
    return 0;
  }
  return (text.length * GLYPH_ADVANCE - 1) * scale;
}
